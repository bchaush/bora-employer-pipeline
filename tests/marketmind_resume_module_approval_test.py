# 1 & 2. All five exact approved wordings present in the protected master,
#        each independently passing the production résumé-module schema.
mm_modules_in_master = {
    m["module_id"]: m for m in master["modules"] if m["module_id"] in APPROVED_WORDING_BY_MODULE
}
assert_true(
    set(mm_modules_in_master.keys()) == set(APPROVED_WORDING_BY_MODULE.keys()),
    f"all five approved MarketMind modules must be present in the master, got {sorted(mm_modules_in_master)}",
)
for module_id, expected_wording in APPROVED_WORDING_BY_MODULE.items():
    module = mm_modules_in_master[module_id]
    assert_true(
        module["wording"] == expected_wording,
        f"{module_id} master wording must be byte-identical to Bora's approved wording",
    )
    schema_errors = list(master_module_schema.iter_errors(module))
    assert_true(
        schema_errors == [],
        f"{module_id} must pass the production resume_module schema: {schema_errors}",
    )
print("PASS 1-2: all five exact approved wordings present in the master and schema-valid.")


# 3 & 4. Exact Claim lineage and exact Evidence lineage preserved.
