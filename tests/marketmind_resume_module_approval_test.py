# 7 & 8. All five modules are reachable through the existing approved-module
#        selection architecture (INCLUDE_MODULE), but are NOT forcibly
#        selected into every derivative (absent from default_module_order).
assert_true(
    set(APPROVED_WORDING_BY_MODULE.keys()).isdisjoint(set(master["default_module_order"])),
    "MarketMind modules must not be part of default_module_order (would force default inclusion)",
)

identity_patch = {
    "patch_id": "PATCH_MM_APPROVAL_TEST_NOOP",
    "target_master_id": master["master_id"],
    "operations": [{"op": "REORDER_MODULES", "module_ids": master["default_module_order"]}],
}
noop_result = build_resume_derivative(
    master=master,
    patch=identity_patch,
    claim_index=CLAIM_INDEX,
    evidence_index=EVIDENCE_INDEX,
    derivative_id="DERIV_MM_APPROVAL_NOOP",
)
assert_true(noop_result["valid"] is True, "identity-patch derivative must build")
noop_included = set(noop_result["derivative"]["included_module_ids"])
assert_false(
    noop_included.intersection(APPROVED_WORDING_BY_MODULE.keys()),
    "MarketMind modules must NOT appear in a derivative that did not explicitly select them",
)

include_ops = [{"op": "INCLUDE_MODULE", "module_id": mid} for mid in APPROVED_WORDING_BY_MODULE]
include_patch = {
    "patch_id": "PATCH_MM_APPROVAL_TEST_INCLUDE",
    "target_master_id": master["master_id"],
    "operations": include_ops,
}
include_result = build_resume_derivative(
    master=master,
    patch=include_patch,
    claim_index=CLAIM_INDEX,
    evidence_index=EVIDENCE_INDEX,
    derivative_id="DERIV_MM_APPROVAL_INCLUDE",
)
assert_true(include_result["valid"] is True, f"explicit-include derivative must build: {include_result.get('errors')}")
include_included = set(include_result["derivative"]["included_module_ids"])
assert_true(
    set(APPROVED_WORDING_BY_MODULE.keys()).issubset(include_included),
    "explicitly selecting MarketMind modules via INCLUDE_MODULE must succeed",
)
assert_true(
    include_result["derivative"]["export_allowed"] is False,
    "export must remain blocked pending human review even when modules are selected",
)
print("PASS 7-8: MarketMind modules are selectable via INCLUDE_MODULE but excluded from every default derivative.")


